import api from './client'
export const getIncidents = (status) => api.get('/incidents/', { params: { status } })
export const getIncident = (id) => api.get(`/incidents/${id}`)
export const createIncident = (data) => api.post('/incidents/', data)
export const updateStatus = (id, data) => api.patch(`/incidents/${id}/status`, data)
export const getEvidences = (id) => api.get(`/incidents/${id}/evidences/`)
export const addEvidence = (id, data) => api.post(`/incidents/${id}/evidences/`, data)
export const lockEvidence = (incId, evId) => api.patch(`/incidents/${incId}/evidences/${evId}/lock`)
export const getCustody = (incId, evId) => api.get(`/incidents/${incId}/evidences/${evId}/custody`)
export const getImpact = (id) => api.get(`/incidents/${id}/impact/`)
export const createImpact = (id, data) => api.post(`/incidents/${id}/impact/`, data)
export const getContainments = (id) => api.get(`/incidents/${id}/containments/`)
export const proposeContainment = (id, data) => api.post(`/incidents/${id}/containments/`, data)
export const reviewContainment = (incId, contId, data) => api.patch(`/incidents/${incId}/containments/${contId}/review`, data)
export const executeContainment = (incId, contId, data) => api.patch(`/incidents/${incId}/containments/${contId}/execute`, data)
export const getRecovery = (id) => api.get(`/incidents/${id}/recovery/`)
export const addRecovery = (id, data) => api.post(`/incidents/${id}/recovery/`, data)
export const updateRecoveryStatus = (incId, recId, data) => api.patch(`/incidents/${incId}/recovery/${recId}/status`, data)
export const confirmRecovery = (incId, recId, data) => api.patch(`/incidents/${incId}/recovery/${recId}/confirm`, data)
export const getCommunications = (id) => api.get(`/incidents/${id}/communications/`)
export const createCommunication = (id, data) => api.post(`/incidents/${id}/communications/`, data)
export const approveCommunication = (incId, commId) => api.patch(`/incidents/${incId}/communications/${commId}/approve`)
export const sendCommunication = (incId, commId) => api.patch(`/incidents/${incId}/communications/${commId}/send`)
export const getPostmortem = (id) => api.get(`/incidents/${id}/postmortem/`)
export const createPostmortem = (id, data) => api.post(`/incidents/${id}/postmortem/`, data)
export const finalizePostmortem = (id) => api.patch(`/incidents/${id}/postmortem/finalize`)
export const verifyContainment = (incId, contId, data) => api.patch(`/incidents/${incId}/containments/${contId}/verify`, data)
export const acknowledgeCommunication = (incId, commId) => api.patch(`/incidents/${incId}/communications/${commId}/acknowledge`)
